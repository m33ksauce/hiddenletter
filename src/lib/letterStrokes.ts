export function getLetterBlueprint(letter: string): LetterBlueprint {
  if (/^[A-Z]$/.test(letter)) {
    const blueprint = U[letter]
    if (blueprint) return blueprint
  }
  if (/^[a-z]$/.test(letter)) {
    const blueprint = L[letter]
    if (blueprint) return blueprint
  }
  const upper = letter.toUpperCase()
  const fromUpper = U[upper]
  if (fromUpper) return fromUpper
  throw new Error(`No stroke blueprint for ${letter}`)
}
